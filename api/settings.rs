use std::collections::HashMap;
use vercel_runtime::{run, Body, Error, Request, Response, StatusCode};

#[tokio::main]
async fn main() -> Result<(), Error> {
    run(handler).await
}

pub async fn handler(req: Request) -> Result<Response<Body>, Error> {
    let uri = req.uri();
    let query_map: HashMap<String, String> = uri
        .query()
        .map(|v| {
            url::form_urlencoded::parse(v.as_bytes())
                .into_owned()
                .collect()
        })
        .unwrap_or_default();

    let profile = query_map
        .get("profile")
        .map(|s| s.as_str())
        .unwrap_or("net");

    let (shadow_quality, fx_quality, water_quality, grass_quality, particles_quality) = match profile {
        "potato" => ("0", "0", "0", "0", "0"),
        "high" => ("2", "2", "1", "1", "1"),
        _ => ("1", "1", "0", "0", "0"),
    };

    let xml_content = format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!-- GTA5VN-System Pro Optimization Profile: {} (Generated by Rust Serverless Engine) -->
<Settings>
  <version value="27" />
  <graphics>
    <ResolutionWidth value="1920" />
    <ResolutionHeight value="1080" />
    <RefreshRate value="144" />
    <Windowed value="2" />
    <VSync value="0" />
    <ShadowQuality value="{}" />
    <ReflectionQuality value="0" />
    <ReflectionMSAA value="0" />
    <WaterQuality value="{}" />
    <ParticleQuality value="{}" />
    <GrassQuality value="{}" />
    <ShaderQuality value="0" />
    <PedVarietyMultiplier value="10" />
    <VehicleVarietyMultiplier value="10" />
    <PostFX value="{}" />
    <DoF value="false" />
    <MotionBlurStrength value="0" />
    <TextureQuality value="0" />
    <AnisotropicFiltering value="0" />
    <FogVolumes value="false" />
    <FXAA value="true" />
    <MSAA value="0" />
    <TXAA value="false" />
    <Lighting_FogVolumes value="false" />
  </graphics>
  <system>
    <AudioDevice value="0" />
    <TimerResolution value="5000" />
  </system>
</Settings>"#,
        profile.to_uppercase(),
        shadow_quality,
        water_quality,
        particles_quality,
        grass_quality,
        fx_quality
    );

    let response = Response::builder()
        .status(StatusCode::OK)
        .header("Content-Type", "application/xml; charset=utf-8")
        .header(
            "Content-Disposition",
            format!("attachment; filename=\"settings_{}.xml\"", profile),
        )
        .header("Access-Control-Allow-Origin", "*")
        .body(xml_content.into())?;

    Ok(response)
}
